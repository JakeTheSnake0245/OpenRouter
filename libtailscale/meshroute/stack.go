const (
	meshNICID = 1

	meshTCPDialTimeout = 10 * time.Second
	meshUDPIdleTimeout = 60 * time.Second
	meshDNSIdleTimeout = 15 * time.Second
	meshPingTimeout    = 3 * time.Second

	// stackMTU matches the MTU of the Tailscale TUN (minimalMTU in
	// wgengine/userspace.go), so TCP MSS negotiation lines up.
	stackMTU = 1280
)

// testHookMeshDial, if non-nil, rewrites forwarding destinations in tests.
var testHookMeshDial func(netip.AddrPort) netip.AddrPort

// meshStack terminates TCP and UDP flows diverted from the TUN and relays
// each one over a socket bound to the right Android network. ICMP echo
// requests are answered by pinging the destination with an unprivileged
// ICMP socket bound to that network.
type meshStack struct {
	ipstack *stack.Stack
	linkEP  *channel.Endpoint
	ctx     context.Context
	cancel  context.CancelFunc

	// writeTUN writes an IPv4 packet back to the device.
	writeTUN func(pkt []byte)

	pingSem syncs.Semaphore
}

func newMeshStack(writeTUN func([]byte)) (*meshStack, error) {
	s := stack.New(stack.Options{
		NetworkProtocols:   []stack.NetworkProtocolFactory{ipv4.NewProtocol},
		TransportProtocols: []stack.TransportProtocolFactory{tcp.NewProtocol, udp.NewProtocol},
	})
	sack := tcpip.TCPSACKEnabled(true)
	s.SetTransportProtocolOption(tcp.ProtocolNumber, &sack)

	ep := channel.New(512, stackMTU, "")
	if err := s.CreateNIC(meshNICID, ep); err != nil {
		return nil, errors.New(err.String())
	}
	// Accept packets for any destination address and reply as that address.
	s.SetPromiscuousMode(meshNICID, true)
	s.SetSpoofing(meshNICID, true)
	s.SetRouteTable([]tcpip.Route{{Destination: header.IPv4EmptySubnet, NIC: meshNICID}})

	ctx, cancel := context.WithCancel(context.Background())
	m := &meshStack{
		ipstack:  s,
		linkEP:   ep,
		ctx:      ctx,
		cancel:   cancel,
		writeTUN: writeTUN,
		pingSem:  syncs.NewSemaphore(32),
	}

	tcpFwd := tcp.NewForwarder(s, 0, 1024, m.acceptTCP)
	s.SetTransportProtocolHandler(tcp.ProtocolNumber, tcpFwd.HandlePacket)
	udpFwd := udp.NewForwarder(s, m.acceptUDP)
	s.SetTransportProtocolHandler(udp.ProtocolNumber, udpFwd.HandlePacket)

	go m.outboundLoop()
	return m, nil
}

func (m *meshStack) close() {
	m.cancel()
	m.linkEP.Close()
	m.ipstack.Close()
}

// inject hands an IPv4 packet that left the device to the stack. pkt is
// not retained.
func (m *meshStack) inject(pkt []byte, kind netKind) {
	if len(pkt) >= header.IPv4MinimumSize && pkt[9] == byte(header.ICMPv4ProtocolNumber) {
		m.handleICMP(pkt, kind)
		return
	}
	pb := stack.NewPacketBuffer(stack.PacketBufferOptions{
		Payload: buffer.MakeWithData(append([]byte(nil), pkt...)),
	})
	m.linkEP.InjectInbound(header.IPv4ProtocolNumber, pb)
	pb.DecRef()
}

// outboundLoop writes packets generated by the stack back to the device.
func (m *meshStack) outboundLoop() {
	for {
		pb := m.linkEP.ReadContext(m.ctx)
		if pb == nil {
			return
		}
		view := pb.ToView()
		pkt := append([]byte(nil), view.AsSlice()...)
		view.Release()
		pb.DecRef()
		m.writeTUN(pkt)
	}
}

func addrPortFromTCPIP(a tcpip.Address, port uint16) netip.AddrPort {
	ip, _ := netip.AddrFromSlice(a.AsSlice())
	return netip.AddrPortFrom(ip.Unmap(), port)
}

func (m *meshStack) acceptTCP(r *tcp.ForwarderRequest) {
	id := r.ID()
	dst := addrPortFromTCPIP(id.LocalAddress, id.LocalPort)
	kind, ok := classifyDivert(dst.Addr())
	if !ok {
		r.Complete(true)
		return
	}

	// Dial first, so a failed dial looks like a refused connection to the
	// app instead of a connection that opens and immediately closes.
	remote, err := dialBound(m.ctx, kind, "tcp4", dst)
	if err != nil {
		noteDialError(kind, err)
		r.Complete(true)
		return
	}

	var wq waiter.Queue
	ep, tcpErr := r.CreateEndpoint(&wq)
	if tcpErr != nil {
		r.Complete(true)
		remote.Close()
		return
	}
	r.Complete(false)
	ep.SocketOptions().SetKeepAlive(true)
	client := gonet.NewTCPConn(&wq, ep)
	proxyTCP(client, remote.(*net.TCPConn))
}

func proxyTCP(client *gonet.TCPConn, remote *net.TCPConn) {
	var wg sync.WaitGroup
	wg.Add(1)
	go func() {
		defer wg.Done()
		io.Copy(remote, client)
		remote.CloseWrite()
	}()
	io.Copy(client, remote)
	client.CloseWrite()
	wg.Wait()
	client.Close()
	remote.Close()
}

func (m *meshStack) acceptUDP(r *udp.ForwarderRequest) bool {
	id := r.ID()
	dst := addrPortFromTCPIP(id.LocalAddress, id.LocalPort)
	kind, ok := classifyDivert(dst.Addr())
	if !ok {
		return true // drop
	}
	var wq waiter.Queue
	ep, err := r.CreateEndpoint(&wq)
	if err != nil {
		return true
	}
	client := gonet.NewUDPConn(&wq, ep)
	go m.relayUDP(client, dst, kind)
	return true
}

func (m *meshStack) relayUDP(client *gonet.UDPConn, dst netip.AddrPort, kind netKind) {
	defer client.Close()
	conn, err := dialBound(m.ctx, kind, "udp4", dst)
	if err != nil {
		noteDialError(kind, err)
		return
	}
	remote := conn.(*net.UDPConn)
	defer remote.Close()

	idle := meshUDPIdleTimeout
	if dst.Port() == 53 {
		idle = meshDNSIdleTimeout
	}
	extend := func() {
		t := time.Now().Add(idle)
		client.SetReadDeadline(t)
		remote.SetReadDeadline(t)
	}
	extend()

	done := make(chan struct{}, 2)
	go func() {
		defer func() { done <- struct{}{} }()
		buf := make([]byte, 65535)
		for {
			n, err := client.Read(buf)
			if err != nil {
				return
			}
			extend()
			if _, err := remote.Write(buf[:n]); err != nil && !isTransientUDPError(err) {
				return
			}
		}
	}()
	go func() {
		defer func() { done <- struct{}{} }()
		buf := make([]byte, 65535)
		for {
			n, err := remote.Read(buf)
			if err != nil {
				if isTransientUDPError(err) {
					continue
				}
				return
			}
			extend()
			if _, err := client.Write(buf[:n]); err != nil {
				return
			}
		}
	}()
	<-done
}

// isTransientUDPError reports whether err is an ICMP-induced error (such as
// a port unreachable from a previous datagram) that should not end the flow.
func isTransientUDPError(err error) bool {
	return errors.Is(err, syscall.ECONNREFUSED) || errors.Is(err, syscall.EHOSTUNREACH) || errors.Is(err, syscall.ENETUNREACH)
}

// dialBound dials dst with a socket bound to the given network. For the
// internet network it falls back to the well-known NAT64 prefix, so rescue
// keeps working on IPv6-only cellular networks.
func dialBound(ctx context.Context, kind netKind, network string, dst netip.AddrPort) (net.Conn, error) {
	if testHookMeshDial != nil {
		dst = testHookMeshDial(dst)
	}
	d := net.Dialer{
		Timeout: meshTCPDialTimeout,
		Control: bindControl(kind),
	}
	c, err := d.DialContext(ctx, network, dst.String())
	if err == nil || kind != netInternet {
		return c, err
	}
	a4 := dst.Addr().As4()
	var a16 [16]byte
	copy(a16[:], []byte{0x00, 0x64, 0xff, 0x9b})
	copy(a16[12:], a4[:])
	nat64 := netip.AddrPortFrom(netip.AddrFrom16(a16), dst.Port())
	if network == "tcp4" {
		network = "tcp6"
	} else {
		network = "udp6"
	}
	if c6, err6 := d.DialContext(ctx, network, nat64.String()); err6 == nil {
		return c6, nil
	}
	return nil, err
}

// handleICMP answers an ICMP echo request by pinging its destination over
// the given network.
func (m *meshStack) handleICMP(pkt []byte, kind netKind) {
	ihl := int(pkt[0]&0x0f) * 4
	if ihl < header.IPv4MinimumSize || len(pkt) < ihl+header.ICMPv4MinimumSize {
		return
	}
	icmpMsg := pkt[ihl:]
	if header.ICMPv4(icmpMsg).Type() != header.ICMPv4Echo {
		return
	}
	if !m.pingSem.TryAcquire() {
		return
	}
	req := append([]byte(nil), pkt...)
	go func() {
		defer m.pingSem.Release()
		if reply := pingOver(kind, req, ihl); reply != nil {
			m.writeTUN(reply)
		}
	}()
}

// buildEchoReply builds an IPv4 ICMP echo reply packet from src to dst.
func buildEchoReply(src, dst [4]byte, id, seq uint16, payload []byte) []byte {
	total := header.IPv4MinimumSize + header.ICMPv4MinimumSize + len(payload)
	b := make([]byte, total)
	ip := header.IPv4(b)
	ip.Encode(&header.IPv4Fields{
		TotalLength: uint16(total),
		TTL:         64,
		Protocol:    uint8(header.ICMPv4ProtocolNumber),
		SrcAddr:     tcpip.AddrFrom4(src),
		DstAddr:     tcpip.AddrFrom4(dst),
	})
	ip.SetChecksum(^ip.CalculateChecksum())
	icmp := header.ICMPv4(b[header.IPv4MinimumSize:])
	icmp.SetType(header.ICMPv4EchoReply)
	icmp.SetCode(0)
	icmp.SetIdent(id)
	icmp.SetSequence(seq)
	copy(icmp.Payload(), payload)
	icmp.SetChecksum(0)
	icmp.SetChecksum(^checksum(icmp))
	return b
}

// checksum computes the Internet checksum of b, without the final
// complement.
func checksum(b []byte) uint16 {
	var sum uint32
	for len(b) >= 2 {
		sum += uint32(binary.BigEndian.Uint16(b))
		b = b[2:]
	}
	if len(b) == 1 {
		sum += uint32(b[0]) << 8
	}
	for sum>>16 != 0 {
		sum = (sum & 0xffff) + (sum >> 16)
	}
	return uint16(sum)
}
